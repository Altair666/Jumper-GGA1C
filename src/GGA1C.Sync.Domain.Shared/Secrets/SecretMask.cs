using System.Linq;

namespace GGA1C.Sync.Secrets;

/// <summary>
/// Как секреты выглядят в интерфейсе и что означает содержимое поля при сохранении.
///
/// Само значение наружу не отдаётся никогда — вместо него приходит маска той же длины,
/// то есть ровно столько точек, сколько символов в сохранённом секрете. Так видно, что
/// секрет есть и какой он длины, а поле при этом можно выделить и стереть: прежний вариант
/// (пустое поле плюс галочка «задан») выглядел как «не заполнено» и не позволял удалить
/// значение вообще.
///
/// Отсюда три исхода при сохранении, см. <see cref="IsMask"/>:
/// маска — оставить как было; пусто — удалить; что-то иное — новое значение.
/// </summary>
public static class SecretMask
{
    /// <summary>Знак маски. Точка посередине строки, а не звёздочка: в поле типа password
    /// браузер и так рисует точки, и маска не выделяется на их фоне.</summary>
    public const char Char = '•';

    /// <summary>Маска длиной в сохранённый секрет; для пустого секрета — пустая строка.</summary>
    public static string For(string? secret)
    {
        return string.IsNullOrEmpty(secret) ? "" : new string(Char, secret.Length);
    }

    /// <summary>
    /// Поле не тронули: в нём только точки. Проверяем не на точное совпадение с маской, а
    /// на «одни точки» — человек мог стереть часть точек, и это тоже не новое значение.
    /// Стереть секрет можно, очистив поле целиком.
    /// </summary>
    public static bool IsMask(string? value)
    {
        return !string.IsNullOrEmpty(value) && value.All(c => c == Char);
    }
}
