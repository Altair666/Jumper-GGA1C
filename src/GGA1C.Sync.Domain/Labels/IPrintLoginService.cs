using System.Threading.Tasks;

namespace GGA1C.Sync.Labels;

/// <summary>
/// Логины в MySQL, которыми GoLabel II забирает этикетки.
///
/// Почему именно так: в GoLabel II **нет ODBC** (проверено по его сборкам), зато есть
/// подключение к MySQL своим драйвером, который лежит в папке программы. То есть на машине
/// с принтером не нужно ни ставить драйвер, ни заводить источник данных — только вписать
/// адрес, базу, логин и пароль.
///
/// Разделение по людям держит сама СУБД: человеку выдаётся право читать **только
/// представление</c> my_labels</c>, а оно отбирает строки по логину, с которым пришло
/// подключение. Чужих строк он не увидит, даже если захочет — прав на саму таблицу у него нет.
///
/// Пароль не хранится: он показывается один раз при выдаче, как ключ виджета. Забыл —
/// выдаётся новый.
/// </summary>
public interface IPrintLoginService
{
    /// <summary>
    /// Логин для этого человека. Это его **почта** — та же, под которой он входит в
    /// Keycloak и Grist, чтобы не заводить человеку ещё одно имя. Если почты нет или она
    /// длиннее, чем позволяет MySQL (32 знака), берётся имя папки с приставкой lbl_.
    /// </summary>
    string LoginFor(string slug, string? email);

    /// <summary>
    /// Создать логин (или сменить ему пароль) и вернуть пароль в открытом виде — один раз.
    /// Заодно проверяет, что представление на месте.
    /// </summary>
    Task<string> IssueAsync(string slug, string? email);

    /// <summary>Удалить логин вместе с правами. Вызывается при удалении учётки.</summary>
    Task DropAsync(string? login);

    /// <summary>Создать или обновить представление <c>my_labels</c>.</summary>
    Task EnsureViewAsync();

    /// <summary>Есть ли такой логин в базе. Нужно интерфейсу: показать, выдан он или нет.</summary>
    Task<bool> ExistsAsync(string? login);
}
