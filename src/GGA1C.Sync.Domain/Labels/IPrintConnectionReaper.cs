using System.Threading.Tasks;

namespace GGA1C.Sync.Labels;

/// <summary>
/// Прибирает за GoLabel II его подключения к MySQL.
///
/// GoLabel на каждое обновление данных открывает новое соединение и прежнее не закрывает —
/// видно в журнале запросов: за несколько нажатий накапливается с десяток спящих сессий.
/// Одному оператору это не мешает, но на десяток рабочих мест упрётся в <c>max_connections</c>,
/// и тогда перестанет подключаться не только печать, но и сам хаб.
///
/// Ограничить человека одним подключением средствами MySQL (<c>MAX_USER_CONNECTIONS</c>)
/// нельзя: сервер тогда отказывает **новому** соединению, то есть ломается как раз
/// обновление. Поэтому лишние убирает хаб: оставляет самое свежее, остальные спящие закрывает.
/// </summary>
public interface IPrintConnectionReaper
{
    /// <summary>
    /// Закрыть лишние спящие подключения печатающих. Возвращает, сколько закрыто.
    /// Подключения самого хаба не трогаются.
    /// </summary>
    Task<int> ReapAsync();
}
